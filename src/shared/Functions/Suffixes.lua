return function(number, precision)
	if number > 999 then
		precision = 2
		local exponent = math.floor(math.log10(number))
		local suffixIndex = math.floor(exponent / 3)
		local scaledNumber = number / (10 ^ (suffixIndex * 3))
		local formattedNumber = string.format("%." .. precision .. "f", scaledNumber)
		return formattedNumber .. (Suffixes[suffixIndex] or "")
	else
		precision = precision or 0
		return string.format("%." .. precision .. "f", number)
	end
end
